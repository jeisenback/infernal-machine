"""Card effects: reading rules text into things the game does.

Rules text is matched sentence by sentence against known templates. A spell gets effects only if every sentence is
understood; otherwise it resolves with no effect and the game reports it as unsupported, instead of doing part of what
the card says. Triggered abilities on permanents ("When this creature enters, draw a card.") use the same templates for
what they do.

The reading is split by purpose, each module building on the ones before it:

    common     rules text as lines and sentences, and the regex pieces the others share
    targets    which cards, permanents or players an effect names
    outcomes   what a spell or ability does: the effect classes and the templates that read them
    statics    rules text that is always on: static abilities, replacement effects, protection, restrictions
    costs      what it costs to cast or play: alternative and additional costs, kicker, reductions, cycling
    triggers   triggered abilities and the events they watch for
    activated  activated abilities: the cost before the colon, and equip-like abilities
    mana       mana abilities
    spells     the effects of an instant or sorcery

The game imports from here, so a name moves between modules without its callers noticing.
"""

